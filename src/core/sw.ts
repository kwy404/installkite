// Generates sw.js: a settings line with the precache list, followed by the
// bundled service worker runtime.
import { DEFAULT_SW_CONFIG, type SwConfig } from '../sw/router.js';
import { readAsset } from './assets.js';
import { precacheVersion, type PrecacheEntry } from './precache.js';

export interface ServiceWorkerOptions extends Partial<Omit<SwConfig, 'version' | 'precache'>> {
  /** Activate new versions right away instead of waiting for "Refresh to update". */
  skipWaiting?: boolean;
  /** Extra scripts to load into the worker (your own push or sync handlers). */
  importScripts?: string[];
}

/** The settings installkite embeds, with defaults left out so the file stays short. */
export function swSettings(entries: Array<Pick<PrecacheEntry, 'url' | 'revision'>>, opts: ServiceWorkerOptions = {}): Record<string, unknown> {
  const settings: Record<string, unknown> = {
    version: precacheVersion(entries),
    precache: entries.map((e) => [e.url, e.revision]),
  };
  const defaults = DEFAULT_SW_CONFIG as unknown as Record<string, unknown>;
  for (const [k, v] of Object.entries(opts)) {
    if (k === 'importScripts' || v === undefined) continue;
    if (JSON.stringify(v) !== JSON.stringify(defaults[k])) settings[k] = v;
  }
  return settings;
}

/** The full text of sw.js. `runtime` defaults to the bundled service worker runtime. */
export function generateServiceWorker(
  entries: Array<Pick<PrecacheEntry, 'url' | 'revision'>>,
  opts: ServiceWorkerOptions = {},
  meta: { version?: string; runtime?: string } = {},
): string {
  const settings = swSettings(entries, opts);
  const runtime = meta.runtime ?? readAsset('sw-runtime.js');
  const lines = [
    `/* Service worker generated by installkite${meta.version ? ` ${meta.version}` : ''}: https://kwy404.github.io/installkite/`,
    ' * Run "npx installkite build" after every site build to refresh the precache list. */',
  ];
  if (opts.importScripts?.length) lines.push(`importScripts(${opts.importScripts.map((s) => JSON.stringify(s)).join(', ')});`);
  lines.push(`self.__INSTALLKITE__ = ${JSON.stringify(settings)};`);
  lines.push(runtime.trim());
  return `${lines.join('\n')}\n`;
}

